RISK_LABEL = {1: "保守", 2: "偏保守", 3: "平衡", 4: "偏激进", 5: "激进"}


def by_asset_class(weights: dict[str, float], classify) -> dict[str, float]:
    """把标的权重按资产类别合并。classify 传 labels.asset_class。"""
    out: dict[str, float] = {}
    for sym, w in weights.items():
        out[classify(sym)] = out.get(classify(sym), 0.0) + w
    return dict(sorted(out.items(), key=lambda kv: -kv[1]))


def missing_symbols(weights: dict[str, float], available: list[str]) -> list[str]:
    """方案里有、但本地没缓存的标的。"""
    have = {s.upper() for s in available}
    return [s for s in weights if s.upper() not in have]
